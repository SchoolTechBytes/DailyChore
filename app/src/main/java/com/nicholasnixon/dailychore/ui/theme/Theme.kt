    extraLarge = RoundedCornerShape(32.dp)
)

/**
 * The app's theme: green/blue colours, Nunito font, rounded shapes.
 *
 * dynamicColor is OFF by default. When on, Android 12+ repaints the app with colours taken from
 * the phone's wallpaper, which would hide our green/blue (that's why it used to look purple).
 */
@Composable
fun DailyChoreTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        shapes = AppShapes,
        content = content
    )
}
